def get_base_item_id(internal_id: str) -> Optional[str]:
    """Return the unfragged base internal ID if this is a fragged item."""
    if not internal_id:
        return None
    upper = internal_id.strip().upper()
    if upper in FRAGGED_ITEM_MAP:
        return FRAGGED_ITEM_MAP[upper]
    if upper.startswith("STARRED_"):
        return upper[8:]
    return None


def get_recipe(internal_id: str) -> Optional[dict[str, int]]:
    """
    Retrieve ingredient requirements for an item by internal ID.
    Returns None if the item is uncraftable (e.g. mob drop, dungeon boss reward).
    """
    if not internal_id:
        return None
    return RECIPES.get(internal_id.strip().upper())


def register_recipe(internal_id: str, ingredients: dict[str, int]) -> None:
    """Dynamically register or override a recipe in the registry."""
    RECIPES[internal_id.strip().upper()] = ingredients


def load_custom_recipes(path: str = "config/recipes.json") -> int:
    """Load external custom recipes from JSON file if available."""
    import json
    import os

    if not os.path.exists(path):
        return 0

    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        count = 0
        if isinstance(data, dict):
            for k, v in data.items():
                if isinstance(v, dict):
                    RECIPES[k.strip().upper()] = {ing.strip().upper(): int(qty) for ing, qty in v.items()}
                    count += 1
        return count
    except Exception:
        return 0


